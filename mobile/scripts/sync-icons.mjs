// Copies the website's icon set (assets/js/icons.js) into the app, so both
// use the same icons. Run from mobile/ after icons change: node scripts/sync-icons.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const mobileDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(mobileDir, "../assets/js/icons.js"), "utf8");

// icons.js only needs `window` and a document that has already loaded.
const window = {};
const document = { readyState: "complete", querySelectorAll: () => [] };
vm.runInNewContext(source, { window, document });

const icons = window.RoadWatchIcons;
const paths = Object.fromEntries(
  icons.names.map((name) => {
    const markup = icons.svg(name);
    return [name, markup.slice(markup.indexOf(">") + 1, markup.lastIndexOf("</svg>"))];
  }),
);

const output =
  "// Generated by scripts/sync-icons.mjs from assets/js/icons.js. Don't edit by hand.\n\n" +
  "export const iconPaths = " +
  JSON.stringify(paths, null, 2) +
  " as const;\n\nexport type IconName = keyof typeof iconPaths;\n";
fs.writeFileSync(path.join(mobileDir, "src/components/iconPaths.ts"), output);
console.log("Synced " + icons.names.length + " icons.");
